import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
p.on('console', m => { if (m.type() === 'error') errors.push('CONSOLE: ' + m.text()); });
p.on('pageerror', e => errors.push('PAGEERROR: ' + e.message));
p.on('requestfailed', r => errors.push('REQFAIL: ' + r.url() + ' ' + r.failure()?.errorText));
p.on('response', r => { if (r.status() >= 400) errors.push('HTTP' + r.status() + ': ' + r.url()); });
await p.goto('http://localhost:3000/settings', { waitUntil: 'domcontentloaded', timeout: 30000 });
await p.waitForTimeout(5000);
const bodyText = await p.locator('body').innerText();
const html = await p.content();
console.log('=== DIAG ===');
console.log('ERRORS_COUNT=', errors.length);
errors.forEach((e,i) => console.log(`[${i}]`, e.slice(0,300)));
console.log('BODY_TEXT_LEN=', bodyText.length);
console.log('BODY_TEXT_HEAD=', JSON.stringify(bodyText.slice(0, 500)));
console.log('HAS_OAUTH_CARDS=', await p.locator('[data-testid="oauth-cards"]').count());
console.log('HAS_SETTINGS_HEADING=', await p.getByRole('heading', { name: /settings|pengaturan/i }).count());
console.log('MAIN_HTML_LEN=', html.length);
await p.screenshot({ path: 'test-results/settings-diag.png', fullPage: true });
await b.close();
